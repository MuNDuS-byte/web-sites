export function getDestinationById(id) {
  return destinations.find((place) => place.id === id) || null
}

export function getRelatedDestinations(currentId, category, limit = 3) {
  const sameCategory = destinations.filter(
    (place) => place.id !== currentId && place.category === category
  )
  const others = destinations.filter(
    (place) => place.id !== currentId && place.category !== category
  )
  return [...sameCategory, ...others].slice(0, limit)
}
